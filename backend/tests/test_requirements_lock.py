"""
The image installs `requirements.lock`, CI installs it plus `requirements-dev.lock`, and
both are compiled by `uv pip compile` from the short input files (docs/tech-stack.md,
*Dependencies*). Nothing re-resolves at build time any more, so a lock that no longer
matches its input would ship silently: a pin bumped in `requirements.txt` without a
recompile changes nothing that is installed. These tests are that staleness check,
offline, plus the two version rules CLAUDE.md holds (`yfinance` >= 1.1.0, `ibflex` 0.15)
and the link that makes CI test what ships.
"""

import re
from pathlib import Path

import pytest
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name
from packaging.version import Version

BACKEND = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND.parent
RUNTIME_IN = BACKEND / "requirements.txt"
RUNTIME_LOCK = BACKEND / "requirements.lock"
DEV_IN = BACKEND / "requirements-dev.txt"
DEV_LOCK = BACKEND / "requirements-dev.lock"
DOCKERFILE = BACKEND / "Dockerfile"
CI = REPO_ROOT / ".github" / "workflows" / "ci.yml"

_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?==([^\s;\\]+)")


def _inputs(path: Path) -> dict[str, Requirement]:
    reqs = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        assert not line.startswith("-"), (
            f"{path.name}: {line!r}. Put options on the compile command, not in the input "
            f"(a hashed -c/-r here would put a plain local pip install into hash mode)."
        )
        req = Requirement(line)
        reqs[canonicalize_name(req.name)] = req
    return reqs


def _lock(path: Path) -> dict[str, dict]:
    """{name: {"version", "hashes", "via"}} from a `uv pip compile --generate-hashes` file."""
    entries: dict[str, dict] = {}
    current = None
    in_via = False
    for raw in path.read_text(encoding="utf-8").splitlines():
        match = _PIN.match(raw)
        if match:
            current = {"version": Version(match.group(2)), "hashes": 0, "via": set()}
            entries[canonicalize_name(match.group(1))] = current
            in_via = False
            continue
        if current is None:
            continue
        stripped = raw.strip()
        if stripped.startswith("--hash=sha256:"):
            current["hashes"] += 1
        elif stripped.startswith("#"):
            body = stripped.lstrip("#").strip()
            if body.startswith("via"):
                in_via = True
                body = body[3:].strip()
            if in_via and body:
                current["via"].add(body)
    return entries


def _header_command(path: Path) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    assert lines[0].startswith("# This file was autogenerated by uv"), (
        f"{path.name} was not written by `uv pip compile`; never edit a lock by hand"
    )
    return lines[1].lstrip("#").strip()


PAIRS = [(RUNTIME_IN, RUNTIME_LOCK), (DEV_IN, DEV_LOCK)]


@pytest.mark.parametrize("source,lock", PAIRS, ids=["runtime", "dev"])
def test_every_input_is_pinned_in_its_lock_at_a_version_it_allows(source, lock):
    locked = _lock(lock)
    for name, req in _inputs(source).items():
        assert name in locked, (
            f"{source.name} requires {req} but {lock.name} has no {name}: recompile "
            f"(docs/tech-stack.md, 'Bumping a dependency')"
        )
        assert req.specifier.contains(locked[name]["version"], prereleases=True), (
            f"{source.name} says {req}, {lock.name} pins {name}=={locked[name]['version']}: "
            f"the lock is stale, recompile it"
        )


@pytest.mark.parametrize("source,lock", PAIRS, ids=["runtime", "dev"])
def test_the_locks_top_levels_are_exactly_the_inputs(source, lock):
    """The other direction: a package removed from the input but still marked as one of
    its top-levels in the lock means the lock was not recompiled."""
    marker = f"-r {source.name}"
    top_levels = {name for name, entry in _lock(lock).items() if marker in entry["via"]}
    assert top_levels == set(_inputs(source)), (
        f"{lock.name} lists {sorted(top_levels)} as coming from {source.name}, which "
        f"requires {sorted(_inputs(source))}: recompile"
    )


@pytest.mark.parametrize("lock", [RUNTIME_LOCK, DEV_LOCK], ids=["runtime", "dev"])
def test_every_locked_package_carries_hashes(lock):
    locked = _lock(lock)
    assert locked, f"no pins parsed from {lock.name}"
    unhashed = sorted(name for name, entry in locked.items() if not entry["hashes"])
    assert not unhashed, (
        f"{lock.name} pins {unhashed} without hashes; --require-hashes refuses"
    )


@pytest.mark.parametrize("lock", [RUNTIME_LOCK, DEV_LOCK], ids=["runtime", "dev"])
def test_the_locks_target_the_images_python_and_platform(lock):
    """Resolved for python:3.11-slim on x86_64 Linux, never for the Windows dev venv —
    and the Python version moves with the Dockerfile's base image and CI's setup-python."""
    image_python = re.search(
        r"^FROM python:(\d+\.\d+)", DOCKERFILE.read_text(encoding="utf-8"), re.M
    ).group(1)
    ci_python = re.search(
        r"python-version:\s*'(\d+\.\d+)'", CI.read_text(encoding="utf-8")
    ).group(1)
    command = _header_command(lock)
    assert f"--python-version {image_python}" in command, (command, image_python)
    assert "--python-platform x86_64-manylinux" in command, command
    assert "--generate-hashes" in command, command
    assert ci_python == image_python, (ci_python, image_python)


def test_the_dev_lock_is_compiled_against_the_runtime_lock():
    """Otherwise a test package could resolve a shared dependency to a version the image
    does not have, and CI would test a combination that never ships (pip would refuse the
    joint install, but only after the push)."""
    assert f"-c {RUNTIME_LOCK.name}" in _header_command(DEV_LOCK)
    runtime, dev = _lock(RUNTIME_LOCK), _lock(DEV_LOCK)
    differing = {
        name: (runtime[name]["version"], dev[name]["version"])
        for name in runtime.keys() & dev.keys()
        if runtime[name]["version"] != dev[name]["version"]
    }
    assert not differing, differing


def test_yfinance_stays_at_or_above_1_1_0():
    """CLAUDE.md rule 1: older yfinance lacks the protections the rate-limit latch relies on."""
    assert _inputs(RUNTIME_IN)["yfinance"].specifier.contains("1.1.0")
    assert not _inputs(RUNTIME_IN)["yfinance"].specifier.contains("1.0.9")
    assert _lock(RUNTIME_LOCK)["yfinance"]["version"] >= Version("1.1.0")


def test_ibflex_is_exactly_0_15():
    """ibflex aborts on unknown attributes; `_sanitize_flex_xml` is written against 0.15."""
    assert str(_inputs(RUNTIME_IN)["ibflex"].specifier) == "==0.15"
    assert _lock(RUNTIME_LOCK)["ibflex"]["version"] == Version("0.15")


def test_the_image_carries_no_test_tooling_and_no_multipart():
    """No upload endpoints (CLAUDE.md), so python-multipart is attack surface with no
    caller; pytest and its plugins are CI's, never production's."""
    runtime = _lock(RUNTIME_LOCK)
    leaked = sorted(
        name
        for name in runtime
        if name.startswith("pytest") or name in {"python-multipart", "coverage"}
    )
    assert not leaked, f"{RUNTIME_LOCK.name} ships {leaked}"


def test_the_image_and_ci_install_the_locks_hash_checked():
    """The point of the lock: production installs exactly what CI tested."""
    dockerfile = DOCKERFILE.read_text(encoding="utf-8")
    assert re.search(
        r"pip install .*--require-hashes -r requirements\.lock\b", dockerfile
    )
    assert not re.search(r"^(COPY|RUN)\b.*requirements(-dev)?\.txt", dockerfile, re.M)
    ci = CI.read_text(encoding="utf-8")
    assert re.search(
        r"pip install --require-hashes -r requirements\.lock -r requirements-dev\.lock\b",
        ci,
    )
    assert not re.search(r"pip install -r requirements(-dev)?\.txt", ci)
